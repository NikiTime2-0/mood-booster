CREATE TABLE IF NOT EXISTS visits (id INTEGER PRIMARY KEY, time TEXT NOT NULL, device TEXT, device_label TEXT);
CREATE INDEX IF NOT EXISTS visits_time ON visits(time);
CREATE TABLE IF NOT EXISTS content (id INTEGER PRIMARY KEY CHECK (id = 1), body TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS previous_content (id INTEGER PRIMARY KEY CHECK (id = 1), body TEXT);
CREATE TABLE IF NOT EXISTS favorites (token TEXT PRIMARY KEY, quote TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS favorites_quote ON favorites(quote);
CREATE TABLE IF NOT EXISTS doll_poll (token TEXT PRIMARY KEY, vote TEXT NOT NULL CHECK (vote IN ('yes', 'no')));
CREATE TABLE IF NOT EXISTS cat_names (token TEXT PRIMARY KEY, name TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS cat_shelves (token TEXT PRIMARY KEY, used INTEGER NOT NULL CHECK (used BETWEEN 0 AND 3));
CREATE TABLE IF NOT EXISTS named_devices (token TEXT PRIMARY KEY, label TEXT NOT NULL);
